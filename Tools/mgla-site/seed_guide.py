def main() -> None:
    db = sqlite3.connect(DB)
    db.row_factory = sqlite3.Row
    db.execute("PRAGMA foreign_keys = ON")
    now = int(time.time())

    db.execute(
        "UPDATE pages SET title=?, intro=?, updated_at=? WHERE slug='guide'",
        ("Инструкция", INTRO, now),
    )

    # wipe previous guide tree
    section_ids = [
        r["id"]
        for r in db.execute("SELECT id FROM sections WHERE page_slug='guide'").fetchall()
    ]
    for sid in section_ids:
        db.execute("DELETE FROM chapters WHERE section_id=?", (sid,))
    db.execute("DELETE FROM sections WHERE page_slug='guide'")

    for s_ord, section in enumerate(SECTIONS):
        cur = db.execute(
            "INSERT INTO sections(page_slug, title, sort_order, published) VALUES(?,?,?,1)",
            ("guide", section["title"], s_ord),
        )
        sid = cur.lastrowid
        for c_ord, ch in enumerate(section["chapters"]):
            db.execute(
                "INSERT INTO chapters(section_id, title, body, sort_order, published) VALUES(?,?,?,?,1)",
                (sid, ch["title"], ch["body"], c_ord),
            )

    db.commit()
    total = db.execute(
        """
        SELECT COUNT(*) AS c FROM chapters c
        JOIN sections s ON s.id=c.section_id WHERE s.page_slug='guide'
        """
    ).fetchone()["c"]
    print(f"guide chapters: {total}")
    db.close()


if __name__ == "__main__":
    main()
